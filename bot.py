# ==================== КНОПКИ ====================
def get_start_keyboard():
    markup = types.InlineKeyboardMarkup()
    btn = types.InlineKeyboardButton("Погнали разбираться", callback_data="start_dialog")
    markup.add(btn)
    return markup

def get_end_keyboard():
    markup = types.InlineKeyboardMarkup()
    btn = types.InlineKeyboardButton("Я понял, пошёл работать", callback_data="end_dialog")
    markup.add(btn)
    return markup

# ==================== ОБРАБОТЧИКИ ====================
@bot.message_handler(commands=['start'])
def start(message):
    if message.chat.type != 'private':
        return
    bot.send_message(message.chat.id, "Привет, братец! Я бот-помощник.", reply_markup=get_start_keyboard())

@bot.callback_query_handler(func=lambda call: call.data == "start_dialog")
def start_dialog(call):
    if call.message.chat.type != 'private':
        return
    bot.edit_message_text(
        chat_id=call.message.chat.id,
        message_id=call.message.message_id,
        text="*Я помогаю в решении частых проблем в работе.*\nВ случае проблем пиши @Remzaa",
        parse_mode="Markdown"
    )
    msg = bot.send_message(
        call.message.chat.id,
        "Ниже пиши свою проблему.\n*Важно вводить в точности как на пульте* *(только первое предложение до точки и без неё)*",
        reply_markup=get_end_keyboard(),
        parse_mode="Markdown"
    )
    last_bot_message[call.from_user.id] = msg.message_id

@bot.callback_query_handler(func=lambda call: call.data == "end_dialog")
def end_dialog(call):
    if call.message.chat.type != 'private':
        return
    user_id = call.from_user.id
    chat_id = call.message.chat.id

    try:
        bot.delete_message(chat_id, call.message.message_id)
    except:
        pass

    if user_id in last_bot_message:
        try:
            bot.delete_message(chat_id, last_bot_message[user_id])
        except:
            pass
        last_bot_message.pop(user_id, None)

    bot.send_message(chat_id, "Диалог завершён. Если что-то ещё понадобится — нажми /start", reply_markup=get_start_keyboard())

@bot.message_handler(func=lambda message: True)
def handle_message(message):
    if message.chat.type != 'private':
        return

    user_id = message.from_user.id
    text = message.text.lower().strip()

    try:
        member = bot.get_chat_member(CLOSED_GROUP_ID, user_id)
        if member.status not in ['member', 'administrator', 'creator']:
            bot.reply_to(message, "Чтобы задавать вопросы, нужно быть участником закрытой группы @ZonaDJI.")
            return
    except:
        bot.reply_to(message, "Ошибка проверки подписки.")
        return

    if text in knowledge:
        msg = bot.reply_to(message, knowledge[text], reply_markup=get_end_keyboard(), parse_mode="Markdown")
        last_bot_message[user_id] = msg.message_id
    else:
        msg = bot.reply_to(message, "Извини, я пока не знаю ответ на этот вопрос.\nДля обучения напиши @Remzaa", reply_markup=get_end_keyboard())
        last_bot_message[user_id] = msg.message_id

print("Бот запущен...")
bot.polling()
